CREATE TABLE IF NOT EXISTS solicitudes_soporte (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  mensaje TEXT NOT NULL CHECK (BTRIM(mensaje) <> '' AND LENGTH(mensaje) <= 2000),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  respuesta TEXT,
  respondida_por INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  respondido_en TIMESTAMPTZ,
  CONSTRAINT solicitudes_soporte_respuesta_ck CHECK (
    (respuesta IS NULL AND respondida_por IS NULL AND respondido_en IS NULL)
    OR (respuesta IS NOT NULL AND respondida_por IS NOT NULL AND respondido_en IS NOT NULL)
  )
);

CREATE INDEX IF NOT EXISTS solicitudes_soporte_usuario_fecha_idx
  ON solicitudes_soporte (usuario_id, creado_en DESC);

CREATE INDEX IF NOT EXISTS solicitudes_soporte_pendientes_idx
  ON solicitudes_soporte (creado_en)
  WHERE respuesta IS NULL;
