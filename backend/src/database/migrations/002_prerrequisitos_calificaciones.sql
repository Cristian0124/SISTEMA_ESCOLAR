CREATE TABLE IF NOT EXISTS materias_pensum (
  codigo VARCHAR(5) PRIMARY KEY,
  nombre VARCHAR(150) NOT NULL,
  semestre SMALLINT NOT NULL CHECK (semestre BETWEEN 1 AND 10),
  creditos SMALLINT NOT NULL CHECK (creditos BETWEEN 1 AND 10)
);

CREATE TABLE IF NOT EXISTS prerrequisitos_materia (
  codigo_materia VARCHAR(5) NOT NULL REFERENCES materias_pensum(codigo) ON DELETE CASCADE,
  codigo_requisito VARCHAR(5) NOT NULL REFERENCES materias_pensum(codigo),
  PRIMARY KEY (codigo_materia, codigo_requisito),
  CHECK (codigo_materia <> codigo_requisito)
);

CREATE TABLE IF NOT EXISTS calificaciones (
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  codigo_materia VARCHAR(5) NOT NULL REFERENCES materias_pensum(codigo),
  nota NUMERIC(3, 1) NOT NULL CHECK (nota BETWEEN 0 AND 5),
  registrada_por INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  actualizada_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (usuario_id, codigo_materia)
);

