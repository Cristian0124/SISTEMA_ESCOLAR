CREATE TABLE IF NOT EXISTS cursos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(10) NOT NULL UNIQUE,
  codigo_pensum VARCHAR(5) NOT NULL REFERENCES materias_pensum(codigo),
  docente_id INTEGER NULL REFERENCES usuarios(id) ON DELETE SET NULL,
  horario VARCHAR(100) NOT NULL,
  cupos_totales INTEGER NOT NULL CHECK (cupos_totales > 0),
  cupos_disponibles INTEGER NOT NULL
    CHECK (cupos_disponibles >= 0 AND cupos_disponibles <= cupos_totales)
);

CREATE INDEX IF NOT EXISTS cursos_codigo_pensum_idx
  ON cursos (codigo_pensum);

