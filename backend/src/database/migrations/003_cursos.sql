-- The inspected database has no existing matriculas; this adds the missing course relation.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'matriculas_curso_id_fkey'
      AND conrelid = 'matriculas'::regclass
  ) THEN
    ALTER TABLE matriculas
      ADD CONSTRAINT matriculas_curso_id_fkey
      FOREIGN KEY (curso_id) REFERENCES cursos(id);
  END IF;
END
$$;

