CREATE TABLE facultades (
 codigo VARCHAR(10) PRIMARY KEY,
 nombre VARCHAR(150) NOT NULL
);
CREATE TABLE carreras (
 codigo VARCHAR(10) PRIMARY KEY,
 facultad_codigo VARCHAR(10) NOT NULL REFERENCES facultades(codigo),
 nombre VARCHAR(150) NOT NULL,
 nivel VARCHAR(30) NOT NULL,
 modalidad VARCHAR(30) NOT NULL,
 fuente TEXT NOT NULL,
 consultado_en DATE NOT NULL
);

CREATE TABLE usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(150) NOT NULL,
  correo VARCHAR(254) NOT NULL,
  password_hash TEXT NOT NULL,
  rol VARCHAR(20) NOT NULL DEFAULT 'estudiante'
    CHECK (rol IN ('estudiante', 'profesor', 'admin')),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  cedula VARCHAR(32) NOT NULL,
  fecha_nacimiento DATE NOT NULL,
  fecha_ingreso DATE NOT NULL,
  nacionalidad VARCHAR(100) NOT NULL,
  genero VARCHAR(50) NOT NULL,
  carrera_codigo VARCHAR(10) REFERENCES carreras(codigo)
);

CREATE UNIQUE INDEX usuarios_correo_normalizado_uq
  ON usuarios (LOWER(BTRIM(correo)));

CREATE UNIQUE INDEX usuarios_cedula_uq
  ON usuarios (BTRIM(cedula))
  WHERE cedula IS NOT NULL;

CREATE TABLE materias (
  codigo VARCHAR(5) PRIMARY KEY,
  nombre VARCHAR(150) NOT NULL
);

CREATE TABLE materias_pensum (
  carrera_codigo VARCHAR(10) NOT NULL REFERENCES carreras(codigo),
  codigo VARCHAR(5) NOT NULL REFERENCES materias(codigo),
  semestre SMALLINT NOT NULL CHECK (semestre BETWEEN 1 AND 10),
  creditos SMALLINT NOT NULL CHECK (creditos BETWEEN 1 AND 10),
  PRIMARY KEY (carrera_codigo, codigo)
);

CREATE INDEX materias_pensum_codigo_idx ON materias_pensum(codigo);

CREATE TABLE prerrequisitos_materia (
  carrera_codigo VARCHAR(10) NOT NULL,
  codigo_materia VARCHAR(5) NOT NULL,
  codigo_requisito VARCHAR(5) NOT NULL,
  PRIMARY KEY (carrera_codigo, codigo_materia, codigo_requisito),
  FOREIGN KEY (carrera_codigo, codigo_materia) REFERENCES materias_pensum(carrera_codigo, codigo) ON DELETE CASCADE,
  FOREIGN KEY (carrera_codigo, codigo_requisito) REFERENCES materias_pensum(carrera_codigo, codigo),
  CHECK (codigo_materia <> codigo_requisito)
);

CREATE FUNCTION plan_del_estudiante(estudiante INTEGER)
RETURNS SETOF materias_pensum LANGUAGE SQL STABLE AS $$
  SELECT plan.* FROM materias_pensum plan
  JOIN usuarios usuario ON usuario.carrera_codigo = plan.carrera_codigo
  WHERE usuario.id = $1
$$;

CREATE FUNCTION materia_del_programa(codigo VARCHAR, estudiante INTEGER)
RETURNS BOOLEAN LANGUAGE SQL STABLE AS $$
  SELECT EXISTS (
    SELECT 1 FROM plan_del_estudiante($2) WHERE codigo = $1
  )
$$;

CREATE TABLE cursos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(10) NOT NULL UNIQUE,
  codigo_pensum VARCHAR(5) NOT NULL REFERENCES materias(codigo),
  docente_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  horario VARCHAR(1000) NOT NULL,
  cupos_totales INTEGER NOT NULL CHECK (cupos_totales > 0),
  cupos_disponibles INTEGER NOT NULL
    CHECK (cupos_disponibles >= 0 AND cupos_disponibles <= cupos_totales)
);

CREATE INDEX cursos_codigo_pensum_idx
  ON cursos (codigo_pensum);

-- ISO: lunes=1, domingo=7. Sin sesiones significa pendiente de revisión.
CREATE TABLE curso_horarios (
  id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  curso_id INTEGER NOT NULL REFERENCES cursos(id) ON DELETE CASCADE,
  dia SMALLINT NOT NULL CHECK (dia BETWEEN 1 AND 7),
  hora_inicio TIME NOT NULL,
  hora_fin TIME NOT NULL,
  CHECK (hora_inicio < hora_fin),
  UNIQUE (curso_id, dia, hora_inicio, hora_fin)
);

-- Solo convierte un día explícito con intervalo completo en formato de 24 horas.
CREATE FUNCTION sincronizar_horario_curso() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE partes TEXT[];
  dias TEXT[] := ARRAY['lunes','martes','miércoles','jueves','viernes','sábado','domingo'];
BEGIN
  DELETE FROM curso_horarios WHERE curso_id = NEW.id;
  partes := regexp_match(lower(trim(NEW.horario)),
    '^(lunes|martes|miércoles|jueves|viernes|sábado|domingo) +([0-9]{1,2}:[0-9]{2}) *- *([0-9]{1,2}:[0-9]{2})$');
  IF partes IS NOT NULL AND partes[2] ~ '^([01]?[0-9]|2[0-3]):[0-5][0-9]$'
    AND partes[3] ~ '^([01]?[0-9]|2[0-3]):[0-5][0-9]$' THEN
    IF partes[2]::time < partes[3]::time THEN
      INSERT INTO curso_horarios(curso_id, dia, hora_inicio, hora_fin)
      VALUES (NEW.id, array_position(dias, partes[1]), partes[2]::time, partes[3]::time);
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER cursos_sincronizar_horario AFTER INSERT OR UPDATE OF horario ON cursos
FOR EACH ROW EXECUTE FUNCTION sincronizar_horario_curso();

CREATE TABLE matriculas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  usuario_id INTEGER NOT NULL
    REFERENCES usuarios(id),

  curso_id INTEGER NOT NULL
    REFERENCES cursos(id),

  curso JSONB NOT NULL
    CHECK (jsonb_typeof(curso) = 'object'),

  estado VARCHAR(20) NOT NULL DEFAULT 'Activa'
    CHECK (estado = 'Activa'),

  fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

  periodo VARCHAR(6) NOT NULL DEFAULT (
    to_char(CURRENT_DATE, 'YYYY') || CASE WHEN EXTRACT(MONTH FROM CURRENT_DATE) <= 6 THEN '-1' ELSE '-2' END
  ),
  UNIQUE (usuario_id, curso_id, periodo)
);

CREATE INDEX matriculas_periodo_curso_idx ON matriculas(periodo, curso_id, estado);

CREATE TABLE calificaciones (
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  codigo_materia VARCHAR(5) NOT NULL REFERENCES materias(codigo),
  nota NUMERIC(4, 2) NOT NULL CHECK (nota BETWEEN 0 AND 5),
  corte_1 NUMERIC(2, 1) CHECK (corte_1 BETWEEN 0 AND 5),
  corte_2 NUMERIC(2, 1) CHECK (corte_2 BETWEEN 0 AND 5),
  corte_3 NUMERIC(2, 1) CHECK (corte_3 BETWEEN 0 AND 5),
  registrada_por INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  actualizada_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (usuario_id, codigo_materia)
);

CREATE TABLE solicitudes_creditos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  periodo VARCHAR(6) NOT NULL,
  creditos INTEGER NOT NULL CHECK (creditos > 0),
  motivo TEXT NOT NULL CHECK (BTRIM(motivo) <> ''),
  estado VARCHAR(12) NOT NULL DEFAULT 'Pendiente'
    CHECK (estado IN ('Pendiente', 'Aprobada', 'Rechazada')),
  solicitado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  revisado_por INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  revisado_en TIMESTAMPTZ,
  CONSTRAINT solicitudes_creditos_revision_ck CHECK (
    (estado = 'Pendiente' AND revisado_por IS NULL AND revisado_en IS NULL)
    OR (estado <> 'Pendiente' AND revisado_por IS NOT NULL AND revisado_en IS NOT NULL)
  )
);

CREATE INDEX solicitudes_creditos_usuario_periodo_idx
  ON solicitudes_creditos (usuario_id, periodo, estado);

CREATE UNIQUE INDEX solicitudes_creditos_una_pendiente_uq
  ON solicitudes_creditos (usuario_id, periodo)
  WHERE estado = 'Pendiente';

CREATE TABLE solicitudes_soporte (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  mensaje TEXT NOT NULL CHECK (BTRIM(mensaje) <> '' AND LENGTH(mensaje) <= 2000),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  respuesta TEXT,
  respondida_por INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  respondido_en TIMESTAMPTZ,
  CONSTRAINT solicitudes_soporte_respuesta_ck CHECK (
    (respuesta IS NULL AND respondida_por IS NULL AND respondido_en IS NULL)
    OR (respuesta IS NOT NULL AND respondida_por IS NOT NULL AND respondido_en IS NOT NULL)
  )
);

CREATE INDEX solicitudes_soporte_usuario_fecha_idx
  ON solicitudes_soporte (usuario_id, creado_en DESC);

CREATE INDEX solicitudes_soporte_pendientes_idx
  ON solicitudes_soporte (creado_en)
  WHERE respuesta IS NULL;

CREATE TABLE sesiones_auth (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  refresh_hash CHAR(64) NOT NULL UNIQUE CHECK (refresh_hash ~ '^[0-9a-f]{64}$'),
  vence_en TIMESTAMPTZ NOT NULL,
  revocada_en TIMESTAMPTZ,
  creada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX sesiones_auth_usuario_idx ON sesiones_auth(usuario_id);
CREATE INDEX sesiones_auth_vencimiento_idx ON sesiones_auth(vence_en);

CREATE TABLE perfiles_usuarios (
  usuario_id INTEGER PRIMARY KEY REFERENCES usuarios(id) ON DELETE CASCADE,
  datos_contacto JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(datos_contacto) = 'object'),
  hoja_vida JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(hoja_vida) = 'object'),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
